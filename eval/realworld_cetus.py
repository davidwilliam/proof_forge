#!/usr/bin/env python3
"""Real-world check for rw-cetus-shlw: Cetus's real Move code at pinned commits, run with the
Sui CLI, compared input by input with the proved Lean component and with the Lean ports.

For each pinned version of `checked_shlw` in CetusProtocol/integer-mate (the original, the
pull request 6 fix and the pull request 7 fix; realworld/tasks/rw-cetus-shlw/task.json), this
script:
  1. assembles a Move package from the project sources at the pinned commits, unmodified:
     integer-mate `sui/sources/*.move` at that commit, and `clmm_math.move` and
     `tick_math.move` (which holds `get_delta_a`) from CetusProtocol/cetus-clmm-interface at its
     pinned commit; only the manifest (realworld/adapters/cetus/Move.toml) and a generated
     test module are ours;
  2. runs `sui move test` on that package: one unit test per input calls the real
     `math_u256::checked_shlw` or `clmm_math::get_delta_a` and prints the result (an aborted
     call is a failed test, recorded as an abort);
  3. builds the executable of the proved component (an accepted Muse repair when one exists,
     otherwise reference/SolutionA.lean) and of the Lean port of the same version, runs both
     on the same inputs, and records where the real code agrees with its port and where it
     differs from the proved component;
  4. checks every real output against the task's requirements (oracle.py mirrors Spec.lean),
     and states each violation as a Lean goal over the protected definitions, checked in the
     Lean kernel;
  5. checks each port's refutation file (witnesses/<port>.lean) in the Lean kernel and prints
     the axioms its theorems use.

Inputs are the documented attack values plus inputs generated by the task oracle (256-bit
shift arguments with the boundary values, u128 prices inside Cetus's tick bounds, u128
liquidity). What is proved: the Lean component accepted by the judge meets every requirement
for every input. What is tested: the real code, input by input. The real code is not proved.

Sources are fetched at run time into PF_REALWORLD_CACHE (default ~/.cache/proofforge-realworld)
and never copied into this repository. Needs git, Docker and the Sui CLI (`sui`).

Usage: realworld_cetus.py [--cases 2000] [--seed 0] [--out results/cetus-1]
"""
import argparse, json, pathlib, random, re, shutil, subprocess, sys, tempfile, time

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "harness"))
sys.path.insert(0, str(ROOT / "eval"))
import binary_check, judge, task as taskmod  # noqa: E402
import realworld  # noqa: E402

TASK = ROOT / "realworld" / "tasks" / "rw-cetus-shlw"
ADAPTER = ROOT / "realworld" / "adapters" / "cetus"
INTERFACE = {"repository": "https://github.com/CetusProtocol/cetus-clmm-interface",
             "commit": "5f1872c9e629050928b2b7c4605828e9203f5a98",
             "files": {"clmm_math.move": "sui/cetus_clmm/sources/math/clmm_math.move",
                       "tick_math.move": "sui/cetus_clmm/sources/math/tick_math.move"}}
PORTS = {"original": "attacks/buggy_original.lean", "pr6": "attacks/pr6_mask_only.lean",
         "pr7": "reference/SolutionA.lean"}
WITNESSES = {"original": "witnesses/buggy_original.lean", "pr6": "witnesses/pr6_mask_only.lean"}

U256 = 2 ** 256
ATTACK = {"sqrt_price_0": 60257519765924248467716150, "sqrt_price_1": 60863087478126617965993239,
          "liquidity": 10365647984364446732462244378333008}
DOCUMENTED = [
    dict(op="delta_a", **ATTACK, round_up=True),                       # the attack deposit (Dedaub)
    dict(op="delta_a", **ATTACK, round_up=False),
    {"op": "shlw", "n": ATTACK["liquidity"] * (ATTACK["sqrt_price_1"] - ATTACK["sqrt_price_0"])},
    {"op": "shlw", "n": 2 ** 192},                                    # pull request 6 counterexample
    {"op": "shlw", "n": 2 ** 192 - 1},
    {"op": "delta_a", "sqrt_price_0": ATTACK["sqrt_price_0"], "sqrt_price_1": ATTACK["sqrt_price_0"] + 2 ** 79,
     "liquidity": 2 ** 113, "round_up": True},                         # liquidity * diff = 2^192
    dict(op="delta_a", sqrt_price_0=ATTACK["sqrt_price_0"], sqrt_price_1=ATTACK["sqrt_price_1"],
         liquidity=10 ** 18, round_up=True),                           # an ordinary deposit
]


def sh(cmd, **kw):
    return subprocess.run(cmd, capture_output=True, text=True, **kw)


def checkout(repo_url, commit):
    """Extract the tree of `commit` into the cache (the repositories have no tags for these
    commits, so the commit itself is checked out)."""
    name = repo_url.rstrip("/").split("/")[-2] + "_" + repo_url.rstrip("/").split("/")[-1]
    repo = realworld.CACHE / "repos" / name
    if not repo.exists():
        repo.parent.mkdir(parents=True, exist_ok=True)
        r = sh(["git", "clone", "-q", "--filter=blob:none", "--no-checkout", repo_url, str(repo)])
        if r.returncode:
            raise RuntimeError(r.stderr)
    full = sh(["git", "-C", str(repo), "rev-parse", "--verify", f"{commit}^{{commit}}"]).stdout.strip()
    if full != commit:
        raise RuntimeError(f"{repo_url}: commit {commit} not found")
    dest = realworld.CACHE / "checkouts" / f"{name}-{commit[:12]}"
    if not dest.exists():
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = pathlib.Path(tempfile.mkdtemp(prefix="pf-src-", dir=realworld.CACHE))
        archive = subprocess.run(["git", "-C", str(repo), "archive", commit], capture_output=True, check=True).stdout
        subprocess.run(["tar", "-x", "-C", str(tmp)], input=archive, check=True)
        tmp.rename(dest)
    return dest


def move_case(i, c):
    """One Move unit test that calls the real routine on case `c` and prints the result."""
    if c["op"] == "shlw":
        return (f"    #[test] fun c{i:06d}() {{ let (v, o) = math_u256::checked_shlw({c['n']}u256); "
                f"debug::print(&Shlw {{ case: {i}, value: v, overflow: o }}); }}")
    up = "true" if c["round_up"] else "false"
    return (f"    #[test] fun c{i:06d}() {{ let a = clmm_math::get_delta_a({c['sqrt_price_0']}u128, "
            f"{c['sqrt_price_1']}u128, {c['liquidity']}u128, {up}); "
            f"debug::print(&DeltaA {{ case: {i}, amount: a }}); }}")


def cases_module(cases):
    return "\n".join([
        "#[test_only]", "module pf_cetus::cases {", "    use integer_mate::math_u256;",
        "    use cetusclmm::clmm_math;", "    use std::debug;", "",
        "    struct Shlw has drop { case: u64, value: u256, overflow: bool }",
        "    struct DeltaA has drop { case: u64, amount: u64 }", ""]
        + [move_case(i, c) for i, c in enumerate(cases)] + ["}", ""])


def assemble(mate_src, iface_src, cases, dest):
    """Package directory: the pinned sources unmodified, our manifest and the test module."""
    if dest.exists():
        shutil.rmtree(dest)
    (dest / "sources" / "integer_mate").mkdir(parents=True)
    (dest / "sources" / "cetus").mkdir(parents=True)
    shutil.copy(ADAPTER / "Move.toml", dest / "Move.toml")
    files = {}
    for f in sorted((mate_src / "sui" / "sources").glob("*.move")):
        shutil.copy(f, dest / "sources" / "integer_mate" / f.name)
        files[f"integer-mate/sui/sources/{f.name}"] = taskmod.sha256(f)
    for name, rel in INTERFACE["files"].items():
        shutil.copy(iface_src / rel, dest / "sources" / "cetus" / name)
        files[f"cetus-clmm-interface/{rel}"] = taskmod.sha256(iface_src / rel)
    (dest / "sources" / "cases.move").write_text(cases_module(cases))
    return files


DEBUG = re.compile(r"\[debug\] 0x0::cases::(Shlw|DeltaA) \{(.*?)\n\}", re.S)
FAIL = re.compile(r"^\[ FAIL\s*\] pf_cetus::cases::c(\d+)$", re.M)


def run_move(pkg, n):
    """Run the unit tests; returns ({case: output}, raw log tail, test summary line)."""
    r = sh(["sui", "move", "test", "--path", str(pkg), "-t", "1", "pf_cetus::cases::"], timeout=3600)
    log = r.stdout + r.stderr
    outs = {}
    for kind, body in DEBUG.findall(log):
        f = dict(re.findall(r"(\w+): (\w+)", body))
        i = int(f["case"])
        outs[i] = ({"value": int(f["value"]), "overflow": f["overflow"] == "true"} if kind == "Shlw"
                   else {"amount": int(f["amount"])})
    details = {int(m.group(1)): m.group(2) for m in
               re.finditer(r"┌── c(\d+) ─+\n(.*?)(?=\n└)", log, re.S)}
    for m in FAIL.finditer(log):
        i = int(m.group(1))
        d = details.get(i, "")
        code = re.search(r"aborted with code (\d+)", d)
        kind = f"abort code {code.group(1)}" if code else "arithmetic error" if "arithmetic error" in d else "failure"
        where = re.search(r"originating in the module (\S+)", d)
        outs[i] = {"amount": None, "abort": kind + (f" in {where.group(1)}" if where else "")}
    summary = next((l for l in log.splitlines() if l.startswith("Test result:")), "")
    return outs, log[-4000:], summary


def verified_candidate(t, out):
    """An accepted Muse repair (out/repair-*/ with a VERIFIED passport.json) if one exists,
    else the build-team reference."""
    for run in sorted(out.glob("repair-*")):
        p = run / "passport.json"
        if p.exists() and json.loads(p.read_text())["status"] == "VERIFIED":
            return run / "final.lean", f"Muse repair {run.name} (Passport {json.loads(p.read_text())['passport_sha256'][:16]})"
    return t.root / "reference" / "SolutionA.lean", "build-team reference (reference/SolutionA.lean, the pull request 7 port)"


def lean_outputs(t, candidate, cases, name):
    """Build the executable from `candidate` in a fresh project and run it on `cases`."""
    ws = judge.load_workspace(str(candidate))
    project = judge.fresh_project(ws, judge.candidate_files(ws), t)
    b = binary_check.build(project, t)
    if b["exit_code"]:
        raise RuntimeError(b["output_tail"])
    sha = (project / "binary.sha256").read_text().strip()
    outs = binary_check.run_cases(project, t.exe, cases, name)
    shutil.rmtree(project, ignore_errors=True)
    return outs, sha


def same(real, lean):
    if "amount" in real:
        return real["amount"] == lean.get("amount")
    return real == lean


def goal(case, out, rid):
    """A Lean statement, checked by the kernel, that the observed output breaks `rid` for every
    shift routine that produces it."""
    if rid == "REQ-SHLW-EXACT":
        return (f"∀ shlw : Shlw, shlw {case['n']} = ({out['value']}, false) → ¬ ShlwExact shlw",
                f"intro shlw h hex; have e := hex {case['n']} (by rw [h]); rw [h] at e; exact absurd e (by decide)")
    if rid == "REQ-SHLW-COMPLETE":
        return (f"∀ shlw : Shlw, shlw {case['n']} = ({out['value']}, true) → ¬ ShlwComplete shlw",
                f"intro shlw h hc; have e := hc {case['n']} (by decide); rw [h] at e; exact absurd e (by decide)")
    pred = {"REQ-DELTA-A-COVERS": "DeltaACovers", "REQ-DELTA-A-TIGHT": "DeltaATight",
            "REQ-DELTA-A-FLOOR": "DeltaAFloor"}.get(rid)
    if pred is None:
        return None
    up = "true" if case["round_up"] else "false"
    args = f"{case['sqrt_price_0']} {case['sqrt_price_1']} {case['liquidity']}"
    stmt = f"∀ shlw : Shlw, getDeltaA shlw {args} {up} = some {out['amount']} → ¬ {pred} shlw"
    proof = ("intro shlw h hc; exact absurd (hc _ _ _ _ h (by decide)) (by decide)" if pred == "DeltaATight"
             else "intro shlw h hc; exact absurd (hc _ _ _ _ h) (by decide)")
    return stmt, proof


def confirm_file(items):
    lines = ["import ClmmMath.Spec", "open ClmmMath", ""]
    spans = []
    for it in items:
        start = len(lines) + 1
        lines += [f"-- {it['label']}", f"example : {it['goal'][0]} := by", f"  {it['goal'][1]}", ""]
        spans.append((start, len(lines)))
    return "\n".join(lines) + "\n", spans


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out", default="results/cetus-1")
    a = ap.parse_args()
    out = (ROOT / a.out).resolve()
    d = out / "real-code"
    d.mkdir(parents=True, exist_ok=True)
    t = taskmod.load(TASK)
    src = t.meta["source"]
    rng = random.Random(a.seed)
    cases = [dict(c) for c in DOCUMENTED] + [t.oracle.gen_case(rng) for _ in range(a.cases)]
    ndoc = len(DOCUMENTED)
    (d / "cases.jsonl").write_text("".join(json.dumps(c) + "\n" for c in cases))
    print(f"[cetus] {len(cases)} inputs ({ndoc} documented)", flush=True)

    candidate, label = verified_candidate(t, out)
    j = judge.judge(str(candidate), task=t)
    if not j["accepted"]:
        raise RuntimeError(f"{candidate} is not accepted by the judge")
    ref_outs, ref_sha = lean_outputs(t, candidate, cases, "reference")
    ref_tree = j["solution_tree_sha256"]
    print(f"[cetus] proved component: {label}, executable {ref_sha[:16]}", flush=True)

    iface = checkout(INTERFACE["repository"], INTERFACE["commit"])
    sui_version = sh(["sui", "--version"]).stdout.strip()
    report = {"spec_task": t.id, "project": src["project"], "repository": src["repository"],
              "license": src["license"], "function": src["function"], "caller": src["caller"],
              "references": src["references"], "sui_version": sui_version, "image": judge.IMAGE,
              "image_id": judge.image_id(), "cases": len(cases), "documented_cases": ndoc, "seed": a.seed,
              "reference": {"candidate": label, "executable_sha256": ref_sha, "solution_tree_sha256": ref_tree},
              "versions": {}}
    versions = [dict(v, status="buggy") for v in src["buggy"]] + [dict(v, status="fixed") for v in src["fixed"]]
    items = []
    for v in versions:
        mate = checkout(src["repository"], v["commit"])
        pkg = realworld.CACHE / "cetus" / f"pkg-{v['commit'][:12]}"
        files = assemble(mate, iface, cases, pkg)
        t0 = time.monotonic()
        real, tail, summary = run_move(pkg, len(cases))
        move_s = round(time.monotonic() - t0, 1)
        port_outs, port_sha = lean_outputs(t, TASK / PORTS[v["tag"]], cases, f"port-{v['tag']}")
        vd = d / v["tag"]
        vd.mkdir(parents=True, exist_ok=True)
        (vd / "outputs.jsonl").write_text("".join(json.dumps(real.get(i)) + "\n" for i in range(len(cases))))
        (vd / "sui-move-test-tail.txt").write_text(tail)
        rep = {"tag": v["tag"], "commit": v["commit"], "lines": v.get("lines"), "status": v["status"],
               "note": v.get("note"), "source_files_sha256": files, "sui_move_test": summary, "move_seconds": move_s,
               "outputs": len(real), "aborts": sum(1 for o in real.values() if o.get("amount", 0) is None),
               "port": PORTS[v["tag"]], "port_executable_sha256": port_sha, "agrees_with_port": 0,
               "differs_from_port": [], "same_as_proved": 0, "differs_but_meets_requirements": 0,
               "violating_cases": 0, "violating_documented": 0, "violating_generated": 0,
               "by_requirement": {}, "witnesses": []}
        seen = set()
        for i, c in enumerate(cases):
            o, p, r = real.get(i), port_outs[i] if i < len(port_outs) else {}, ref_outs[i]
            if o is None:
                rep.setdefault("missing", []).append(i)
                continue
            if same(o, p):
                rep["agrees_with_port"] += 1
            else:
                rep["differs_from_port"].append({"case": i, "input": c, "real": o, "port": p})
            viol = t.oracle.check(c, {k: x for k, x in o.items() if k != "abort"})
            if not viol:
                rep["same_as_proved" if same(o, r) else "differs_but_meets_requirements"] += 1
                continue
            rep["violating_cases"] += 1
            rep["violating_documented" if i < ndoc else "violating_generated"] += 1
            for rid, msg in viol:
                rep["by_requirement"][rid] = rep["by_requirement"].get(rid, 0) + 1
                if i < ndoc or rid not in seen:
                    w = {"case": i, "documented": i < ndoc, "requirement": rid, "message": msg, "input": c,
                         "output": o, "proved_output": r, "lean_goal": goal(c, o, rid)}
                    rep["witnesses"].append(w)
                    items.append({"label": f"{v['tag']} case {i}, {rid}", "goal": w["lean_goal"], "w": w})
                    if i >= ndoc:
                        seen.add(rid)
        report["versions"][v["tag"]] = rep
        print(f"[cetus] {v['tag']} ({v['status']}, {v['commit'][:12]}): {summary}; {rep['violating_cases']} violating "
              f"({rep['violating_documented']} documented); agrees with its Lean port on {rep['agrees_with_port']} "
              f"of {len(cases)}; {rep['by_requirement']}", flush=True)

    # Confirm every recorded witness in the Lean kernel.
    items = [it for it in items if it["goal"]]
    text, spans = confirm_file(items)
    (d / "Confirm.lean").write_text(text)
    ok, tail = realworld.lean_check(t, candidate, {"Confirm.lean": text})["Confirm.lean"] if items else (True, "")
    bad = realworld.failed_examples(tail, "Confirm.lean", spans) if not ok else set()
    if not ok and not bad:
        bad = set(range(len(items)))
    for k, it in enumerate(items):
        it["w"]["confirmed_in_lean"] = k not in bad
    report["lean_confirmation"] = {"file": "real-code/Confirm.lean", "goals": len(items),
                                   "checked": len(items) - len(bad), "output_tail": tail}

    # Ports: verdicts from validation.json and kernel refutations with their axioms.
    val = json.loads((TASK / "validation.json").read_text())
    ports = {}
    for tag, wf in WITNESSES.items():
        port = TASK / PORTS[tag]
        att = val["checks"]["attacks"].get(port.name, {})
        text = (TASK / wf).read_text()
        names = re.findall(r"^theorem\s+(\S+)", text, re.M)
        text += "\n" + "".join(f"#print axioms {n}\n" for n in names)
        res = realworld.lean_check(t, port, {"Refute.lean": text})["Refute.lean"]
        axioms = {n: sorted(x.strip() for x in m.group(1).split(",")) if m.group(1) else []
                  for n in names for m in [re.search(rf"'{re.escape(n)}' (?:depends on axioms: \[([^\]]*)\]|does not depend on any axioms)",
                                                     res[1].replace("\n", " "))] if m}
        ports[tag] = {"port": f"realworld/tasks/{t.id}/{PORTS[tag]}", "note": att.get("expected", {}).get("note"),
                      "judge": att.get("judge"), "judge_reasons": att.get("judge_reasons"), "binary": att.get("binary"),
                      "violations": att.get("violations"), "witness": att.get("witness"),
                      "kernel_refutation": f"realworld/tasks/{t.id}/{wf}", "kernel_refutation_checked": res[0],
                      "theorem_axioms": axioms, "lean_output_tail": res[1]}
        print(f"[cetus] port {tag}: judge {att.get('judge')}, binary {att.get('binary')}, kernel refutation "
              f"{'checked' if res[0] else 'FAILED'}, axioms {axioms}", flush=True)
    report["ports"] = ports
    report["validation"] = {"passed": val.get("passed"),
                            "references": {k: {"judge": x["judge"], "binary": x["binary"]}
                                           for k, x in val["checks"]["references"].items()}}
    report["generated"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    (d / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(f"wrote {d / 'report.json'}")


if __name__ == "__main__":
    main()
